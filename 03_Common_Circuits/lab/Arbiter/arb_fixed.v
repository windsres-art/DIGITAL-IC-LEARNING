// =============================================================================
// 固定优先级仲裁器：bit 0 优先级最高
//   gnt = req & ~(req - 1)：req 减 1 会把最低位的 1 变 0、它下面的 0 全变 1，
//   取反再和 req 相与，只剩最低位的那个 1（独热）
//   纯组合；req 全 0 时 gnt 全 0
// =============================================================================
module arb_fixed #(
    parameter N = 4
)(
    input  [N-1:0] req,
    output [N-1:0] gnt
);
    assign gnt = req & ~(req - {{(N-1){1'b0}}, 1'b1});
endmodule
