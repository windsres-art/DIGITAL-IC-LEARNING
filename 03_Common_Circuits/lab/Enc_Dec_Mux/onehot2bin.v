// =============================================================================
// 独热码 → 二进制编码器（非优先）
//   前提：输入保证独热。bin 的第 j 位 = 所有"下标第 j 位为 1"的输入位相或
//   例 N = 8：bin[0] = oh[1]|oh[3]|oh[5]|oh[7]，每一位只是一个 N/2 输入的或门
//   没有优先级链，比优先编码器小、快；输入多热时输出是各下标的按位或（无意义值）
// =============================================================================
module onehot2bin #(
    parameter N = 8,
    parameter W = (N > 1) ? $clog2(N) : 1
)(
    input      [N-1:0] oh,
    output reg [W-1:0] bin
);
    integer i;
    always @(*) begin
        bin = {W{1'b0}};
        for (i = 0; i < N; i = i + 1)
            if (oh[i]) bin = bin | i[W-1:0];
    end
endmodule
