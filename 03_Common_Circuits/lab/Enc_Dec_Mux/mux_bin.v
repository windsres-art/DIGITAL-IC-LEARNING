// =============================================================================
// 参数化 N 选 1 MUX（二进制选择），每路 W bit
//   Verilog-2001 端口不能是二维数组，所以 N 路数据拼成一个 N*W 位的向量：
//   第 i 路是 din[i*W +: W]
//   N 不是 2 的幂时 sel 可能越界（如 N = 5，sel = 5..7）：仿真输出 X，
//   综合结果由工具决定——需要确定值时要显式处理越界
// =============================================================================
module mux_bin #(
    parameter N = 8,
    parameter W = 8,
    parameter S = (N > 1) ? $clog2(N) : 1
)(
    input  [N*W-1:0] din,
    input  [S-1:0]   sel,
    output [W-1:0]   dout
);
    assign dout = din[sel*W +: W];
endmodule
