// =============================================================================
// 参数化译码器：W 位二进制 → 2^W 位独热，带使能
//   把 en 放在第 0 位再左移 in 位：en = 0 时全 0，en = 1 时第 in 位为 1
//   一行写完，位宽随 W 自动变化；等价于 2^W 个 (in == k) & en 比较器
// =============================================================================
module decoder #(
    parameter W = 3
)(
    input  [W-1:0]      in,
    input               en,
    output [(1<<W)-1:0] out
);
    assign out = {{((1 << W) - 1){1'b0}}, en} << in;
endmodule
