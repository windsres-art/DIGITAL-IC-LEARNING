// =============================================================================
// Gray 码转二进制（组合逻辑），逐级写法
//   b[i] = g[N-1] ^ g[N-2] ^ ... ^ g[i]   （从最高位到第 i 位的前缀异或）
//   逐级 b[i] = b[i+1] ^ g[i]，面试最常写。
//   b[0] 要经过 N-1 级异或，是一条长链；宽指针可用 gray2bin_log.v 的对数级写法
//
//   常见错误：把逆变换也写成 b = g ^ (g >> 1)——那是又做了一次正变换
// =============================================================================
module gray2bin #(
    parameter N = 4
)(
    input      [N-1:0] gray,
    output reg [N-1:0] bin
);
    integer i;
    always @(*) begin
        bin[N-1] = gray[N-1];
        for (i = N - 2; i >= 0; i = i - 1)
            bin[i] = bin[i+1] ^ gray[i];
    end
endmodule
