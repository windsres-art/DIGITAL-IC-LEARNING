// =============================================================================
// 二进制转 Gray 码（组合逻辑）
//   g[i] = b[i+1] ^ b[i]，最高位 g[N-1] = b[N-1]
//   写成向量就是 g = b ^ (b >> 1)：每一位只看自己和高一位，一级异或，没有长链
//   注意：输出是组合逻辑。要跨时钟域时必须先寄存再送出去（见 README 第 1.5 节）
// =============================================================================
module bin2gray #(
    parameter N = 4
)(
    input  [N-1:0] bin,
    output [N-1:0] gray
);
    assign gray = bin ^ (bin >> 1);
endmodule
